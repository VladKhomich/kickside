local test = require("test")
local source = require("source")
local fixture = require("fixture")
return {run = test.run_cases(function()
    test.describe("post-migration owner continuation", function()
        test.before_each(function() fixture.reset(nil) end)
        test.it("wakes retention after migrations even before lifecycle starts", function()
            local result = source.run()
            test.eq(result.status, "success")
            test.eq(fixture.calls, 1)
            test.eq(fixture.provisions, 1)
        end)
        test.it("reports notification failure before lifecycle convergence", function()
            fixture.reset(errors.new({kind = errors.UNAVAILABLE, message = "retention unavailable"}))
            local result = source.run()
            test.eq(result.status, "error")
            test.not_nil((result.message:find("retention migration wake failed", 1, true)))
            test.eq(fixture.calls, 1)
            test.eq(fixture.provisions, 0)
        end)
        test.it("fails startup if system component provisioning fails", function()
            fixture.reset(nil, errors.new({kind = errors.UNAVAILABLE, message = "grant unavailable"}))
            local result = source.run()
            test.eq(result.status, "error")
            test.not_nil((result.message:find("grant unavailable", 1, true)))
            test.eq(fixture.provisions, 1)
        end)
    end)
end)}
